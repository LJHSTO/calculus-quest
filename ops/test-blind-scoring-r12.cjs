'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const bank=require('../lib/assessments/functions-limits-r12'),tool=require('./functions-limits-blind-scoring-r12');
const rows=['pre','post'].flatMap(phase=>['X','Y'].map((form,i)=>({id:phase+'-'+i,user_id:'synthetic-private-owner',question_id:bank.questions(phase,form)[3].id,phase,response:'定义域不同；原式在这个输入没有定义。'})));
const exported={tables:{quiz_results:rows}},packet=tool.packet(exported);
assert.equal(packet.rating.items.length,4);assert.equal(packet.mapping.rows.length,4);
assert.ok(packet.mapping.rows.every(r=>r.instrumentVersion===bank.version));
assert.doesNotMatch(JSON.stringify(packet.rating),/synthetic-private-owner|userId|questionId|instrumentVersion|"arm"/);
assert.ok(packet.rating.items.every(r=>r.material.criteria.length===4));
assert.throws(()=>tool.packet({tables:{quiz_results:[]}}),/未生成空评分包/);
assert.throws(()=>tool.packet({tables:{quiz_results:rows.map(r=>({...r,question_id:r.question_id.replace('fl-r12-','fl-r11-')}))}}),/题库版本/);
const rate=(name,values)=>({...structuredClone(packet.rating),rater:name,items:packet.rating.items.map(item=>({...structuredClone(item),points:[...values]}))});
const a=rate('R1',[1,1,0,0]),b=rate('R2',[1,1,1,0]),judge=rate('ADJ',[1,1,1,1]);
assert.ok(tool.reconcile(packet.mapping,a,b).records.every(r=>r.status==='needs_adjudication'));
assert.ok(tool.reconcile(packet.mapping,a,b,judge).records.every(r=>r.score===4));
const tampered=structuredClone(a);tampered.items[0].material.prompt+='改变题意';assert.throws(()=>tool.validateRating(tampered,packet.mapping),/不得修改/);
const out=fs.mkdtempSync(path.join(process.env.TEMP||process.cwd(),'cq-r12-blind-')),target=path.join(out,'合成评分包');
const saved=tool.prepare(exported,target);assert.equal(saved.rating.items.length,4);
assert.ok(fs.readFileSync(path.join(target,'仅交评分者甲','盲评材料.html'),'utf8').includes('定义域不同'));
assert.throws(()=>tool.prepare(exported,target),/必须使用新目录/);
console.log('r12盲评回归通过：四条合成简答实际生成、拒绝空包/错版本、身份隔离、双评裁决和材料拒篡改；临时证据：'+out);
