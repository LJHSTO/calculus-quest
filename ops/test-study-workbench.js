"use strict";
const assert = require("node:assert/strict"), fs = require("node:fs"), path = require("node:path");
const { createWorkbench, sequenceFor } = require("../lib/study-workbench");
async function main() {
  const SQL = await require("sql.js")(); let sql = new SQL.Database();
  let generation = 1;
  const db = { getDbSync: () => sql, saveNow() {}, currentLearningGeneration: () => generation };
  const env = { NODE_ENV: "test", PROACTIVE_STUDY_WORKBENCH: "recheck", PROACTIVE_STUDY_SEED: "synthetic-study-check-seed", PROACTIVE_STUDY_PROTOCOL_ID: "recheck-unit-tests" };
  let wb = createWorkbench({ db, env }); const checks = [];
  const record = name => { checks.push(name); console.log(`通过：${name}`); };
  for (let i = 0; i < 30; i += 2) {
    const a = sequenceFor({ seed: env.PROACTIVE_STUDY_SEED, stratum: "low", ordinal: i });
    const b = sequenceFor({ seed: env.PROACTIVE_STUDY_SEED, stratum: "low", ordinal: i + 1 });
    assert.equal(a.values.reduce((s, x) => s + x, 0), 3);
    assert.ok(a.values.every((x, j) => x + b.values[j] === 1));
  }
  record("分层互补序列：每人3/3，每对各知识点平衡");
  let a = wb.start("synthetic-a", { acknowledged: true }), b = wb.start("synthetic-b", { acknowledged: true });
  assert.equal(wb.exportData().sessions[0].units.length, 6);
  assert.equal(wb.exportData().sessions[0].units.filter(x => x.status === "assigned_not_entered").length, 5);
  assert.ok(!JSON.stringify(a).includes('"correct"') && !JSON.stringify(a).includes('"condition"'));
  record("预先记录全部六单元，学生响应不包含答案或分组");
  const act = (id, state, action, extra = {}) => wb.act(id, { action, revision: state.session.revision, fingerprint: state.protocol.fingerprint, ...extra });
  const answer = (id, state, response) => act(id, state, "answer", { probeId: state.session.probe.id, response });
  const stale = a;
  a = answer("synthetic-a", a, "0"); b = answer("synthetic-b", b, "0");
  assert.throws(() => answer("synthetic-a", stale, "1"), e => e.code === "study_stale");
  assert.throws(() => act("synthetic-a", a, "continue"), e => e.code === "study_explore_too_short");
  await new Promise(r => setTimeout(r, 1050));
  a = act("synthetic-a", a, "continue"); b = act("synthetic-b", b, "continue");
  assert.equal(wb.protects("synthetic-a"), true);
  a = answer("synthetic-a", a, "1"); b = answer("synthetic-b", b, "1");
  const sessions = wb.exportData().sessions;
  assert.deepEqual(sessions.map(x => x.units[0].decision.action).sort(), ["cancel", "present"]);
  assert.ok(sessions.every(x => x.units[0].probes.t1.serverGraded && x.units[0].decision.currentSnapshot.id !== x.units[0].decision.initialSnapshot.id));
  record("同一初始错误和独立成功，在两条件下真实产生投递与取消");
  const visibleId = a.session.stage === "support" ? "synthetic-a" : "synthetic-b";
  let v = wb.state(visibleId);
  assert.throws(() => act(visibleId, v, "exposure", { fraction: .5, visibleDurationMs: 200 }), e => e.code === "study_exposure_invalid");
  v = act(visibleId, v, "exposure", { fraction: .5, visibleDurationMs: 1000 });
  v = act(visibleId, v, "close");
  assert.equal(v.session.stage, "outcome"); assert.equal(v.session.help, null);
  v = answer(visibleId, v, "skip");
  assert.throws(() => act(visibleId, v, "survey", { answers: { interruption: 0, control: 2, effort: 2 } }), e => e.code === "study_survey_invalid");
  v = act(visibleId, v, "survey", { answers: { interruption: null, control: 4, effort: 3 } });
  const completed = wb.exportData().sessions.find(x => x.userId === visibleId).units[0];
  assert.equal(completed.probes.outcome.correct, null); assert.equal(completed.survey.interruption, null);
  assert.equal(completed.exposure.readingEstablished, false);
  record("曝光门槛、关闭后停止、跳过与缺失值保持独立语义");
  const before = wb.state(visibleId);
  const bytes = sql.export(); sql.close(); sql = new SQL.Database(bytes);
  wb = createWorkbench({ db, env }); assert.deepEqual(wb.state(visibleId), before);
  const changed = createWorkbench({ db, env: { ...env, PROACTIVE_STUDY_SEED: "another-synthetic-seed" } });
  assert.throws(() => changed.state(visibleId), e => e.code === "study_protocol_changed");
  assert.throws(() => changed.start("new-user", { acknowledged: true }), e => e.code === "study_protocol_changed");
  record("持久化恢复、旧请求拒绝和协议漂移拒绝");
  let c = wb.start("synthetic-c", { acknowledged: true }); c = answer("synthetic-c", c, "0");
  c = act("synthetic-c", c, "request_help"); c = act("synthetic-c", c, "dismiss_manual_help");
  assert.equal(c.session.help, null); await new Promise(r => setTimeout(r, 1050));
  c = act("synthetic-c", c, "continue"); c = answer("synthetic-c", c, "1");
  const cUnit = wb.exportData().sessions.find(x => x.userId === "synthetic-c").units[0];
  assert.equal(cUnit.probes.t1.independent, false); assert.equal(cUnit.decision.recovery, "unknown");
  c = act("synthetic-c", c, "withdraw"); assert.equal(c.session.stage, "withdrawn");
  assert.throws(() => act("synthetic-c", c, "continue"), e => e.code === "study_closed");
  record("主动求助污染不冒充独立恢复，退出为终止状态");
  let d = wb.start("synthetic-d", { acknowledged: true }); d = answer("synthetic-d", d, "1");
  await new Promise(r => setTimeout(r, 1050)); d = act("synthetic-d", d, "continue"); d = answer("synthetic-d", d, "skip");
  assert.equal(wb.exportData().sessions.find(x => x.userId === "synthetic-d").units[0].decision.action, "silent");
  assert.equal(d.session.stage, "outcome"); record("无候选仍记录共同边界与独立结果流程");
  const placement = createWorkbench({ db, env: { ...env, PROACTIVE_STUDY_WORKBENCH: "placement", PROACTIVE_STUDY_PROTOCOL_ID: "placement-check" } });
  let p = placement.start("synthetic-placement", { acknowledged: true });
  p = placement.act("synthetic-placement", { action: "answer", revision: p.session.revision, fingerprint: p.protocol.fingerprint, probeId: p.session.probe.id, response: "0", condition: "attacker-choice" });
  const assigned = placement.exportData().sessions[0].units[0].condition; assert.ok(["sidebar", "inline"].includes(assigned));
  assert.throws(() => createWorkbench({ db, env: { ...env, NODE_ENV: "production" } }), /非生产/);
  generation = 2;
  assert.throws(() => wb.state("synthetic-d"), e => e.code === "study_generation_changed");
  record("客户端不能改条件，工程题库禁止生产启用");
  const out = path.resolve(__dirname, "../output/OpenMAIC迁移与研究方案-2026-10-17"); fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, "共同探针与研究状态验收.json"), JSON.stringify({ passed: true, generatedAt: new Date().toISOString(), checks, dataClass: "synthetic_engineering" }, null, 2));
  sql.close();
}
main().catch(e => { console.error(e); process.exitCode = 1; });
