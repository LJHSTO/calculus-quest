function review(question) {
  if (question.instrumentVersion !== "v14-c3-assessments-r3") return null;
  const explanations = items[question.id];
  if (!explanations || explanations.length !== question.options?.length) return null;
  return {
    feedbackVersion: version,
    analysis: question.options.map((option, index) =>
      `选项${option.value}（${question.answer.includes(option.value) ? "应选" : "不应选"}）：${explanations[index]}`
    ).join("\n\n")
  };
}
module.exports = { version, review };
