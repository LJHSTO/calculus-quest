    q.answer = [];
    q.points = 10;
    q.analysis = i === 9
      ? `不能断定。还须确认${isPre ? "右" : "左"}极限存在且等于${isPre ? 3 : 6}，因为双侧极限要求两侧极限存在且相等。`
      : `现在不连续。应设为${isPre ? 4 : 2}，因为连续要求函数值有定义且等于两侧共同的极限。`;
    q.referenceAnswer = q.analysis;
    q.commentPrompt = i === 9
      ? "共10分：判断不能直接断定2分；说明另一侧极限存在3分；等于已知极限3分；给出双侧极限条件2分。"
      : "共10分：判断不连续2分；正确补值或改值4分；说明函数值应等于共同极限4分。";
